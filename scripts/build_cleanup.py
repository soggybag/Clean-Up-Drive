"""Clean-Up Drive: breadboard schematic. A Flatline / Punch Line style optical drive whose gain follows the
CLEAN pick envelope: hard picking drives the clipping diodes, soft picking and decays clean up.
  - U1A: clean input buffer (DRY), feeds both the drive stage and the detector (feed-forward = no runaway)
  - U1B: drive stage. Gain = 1 + R5 / (ground legs). DRIVE sets the resting gain; the LDR (through DEPTH)
         adds gain as you pick harder. Clipping diodes in the feedback cap the output at about +-0.6 V
         (Si) or +-1.8 V (red LED), so the op-amp itself never clips.
  - U2: detector, the Flatline+ side chain fed from DRY through SENSE (x0 to x20 differential)
  - TONE (hi-cut) and VOLUME
Through-hole parts for the breadboard; no footprints.
usage: build_cleanup.py <out.kicad_sch>"""
from sch import *
import sys
OUT = sys.argv[1]
g = lambda n: round(n * 2.54, 3)
s = Sheet('CleanUpDrive', 'A1')
W = lambda *p: s.wire(*p)
P = s.P
def GND(p): s.power('GND', p)
def V9(p): s.power('+9V', p)
def lab(n, p, side='r'): s.label(n, p, side)
def Rh(ref, v, cx, y, d=''): s.part(ref, 'Device', 'R', v, cx, y, 90, desc=d, text='t')
def Rv(ref, v, x, cy, side='r', d=''): s.part(ref, 'Device', 'R', v, x, cy, 0, desc=d, text=side)
def Ch(ref, v, cx, y, d=''): s.part(ref, 'Device', 'C', v, cx, y, 90, desc=d, text='t')
def Cv(ref, v, x, cy, side='r', d=''): s.part(ref, 'Device', 'C', v, x, cy, 0, desc=d, text=side)
def CPv(ref, v, x, cy, side='r', d=''): s.part(ref, 'Device', 'C_Polarized', v, x, cy, 0, desc=d, text=side)
def POT(ref, v, name, x, y, mirror='x', text=None):
    s.part(ref, 'Device', 'R_Potentiometer', v, x, y, 0, mirror=mirror, desc=name, extra={'Panel': name},
           text=text or ((x + g(2), y - g(1)), (x + g(2), y + g(0.5)), 'left'))
def OP(ref, part, unit, x, y): s.part(ref, 'Amplifier_Operational', part, part, x, y, 0, unit=unit, text='ic')
def rheo_to_vb(ref, v, name, x, top, label_side='l'):
    """pot as a rheostat: pin 3 at `top`, wiper tied to pin 1, pin 1 to VB"""
    POT(ref, v, name, x, top + 3.81, text=((x - g(5), top + g(1)), (x - g(5), top + g(2.5)), 'right'))
    w2 = P(ref, '2'); p1 = P(ref, '1')
    W(w2, (w2[0] + g(1), w2[1]), (w2[0] + g(1), p1[1] + g(1)), (p1[0], p1[1] + g(1)))
    W(p1, (p1[0], p1[1] + g(2))); lab('VB', (p1[0], p1[1] + g(2)), label_side)
    return P(ref, '3')

# ================================================================ POWER + BIAS
s.box('POWER + BIAS + JACKS', g(4), g(6), g(38), g(62))
lab('9V_IN', (g(7), g(12)), 'l')
s.part('D1', 'Device', 'D_Schottky', '1N5817', g(12), g(12), 180, desc='Reverse-polarity protection', text='t')
W((g(7), g(12)), P('D1', '2')); W(P('D1', '1'), (g(18), g(12)))
V9((g(18), g(12))); s.power('PWR_FLAG', (g(18), g(12)))
W((g(18), g(12)), (g(30), g(12)))
CPv('C1', '100u', g(22), g(15.5), d='Supply reservoir'); W((g(22), g(12)), P('C1', '1')); GND(P('C1', '2'))
Cv('C2', '100n', g(26), g(15.5), d='U1/U2 decoupling (one per chip on the breadboard)'); W((g(26), g(12)), P('C2', '1')); GND(P('C2', '2'))
Cv('C3', '100n', g(30), g(15.5)); W((g(30), g(12)), P('C3', '1')); GND(P('C3', '2'))
Rv('R1', '10k', g(9), g(26)); V9(P('R1', '1'))
Rv('R2', '10k', g(9), g(34)); GND(P('R2', '2'))
W(P('R1', '2'), P('R2', '1'))
W((g(9), g(30)), (g(15), g(30)), (g(15), g(33.5) - 3.81)); CPv('C4', '47u', g(15), g(33.5), d='VB filter'); GND(P('C4', '2'))
W((g(15), g(30)), (g(19), g(30))); lab('VB', (g(19), g(30))); s.power('PWR_FLAG', (g(19), g(30)))
OP('U1', 'OPA2134', 3, g(26), g(40)); V9(P('U1', '8')); GND(P('U1', '4'))
OP('U2', 'TL072', 3, g(33), g(40)); V9(P('U2', '8')); GND(P('U2', '4'))
s.text('U1 OPA2134 or TL072 (pin-compatible: A/B them)', g(5), g(60))
s.part('J1', 'Connector_Generic', 'Conn_01x02', '9V / GND', g(8), g(47), 180, text=((g(6), g(44)), (g(6), g(45.5)), 'right'))
q = P('J1', '1'); W(q, (q[0] + g(3), q[1])); lab('9V_IN', (q[0] + g(3), q[1]))
q = P('J1', '2'); W(q, (q[0] + g(3), q[1])); GND((q[0] + g(3), q[1]))
s.power('PWR_FLAG', (q[0] + g(3), q[1]))
s.part('J2', 'Connector_Generic', 'Conn_01x03', 'IN / OUT / GND', g(8), g(28) + g(26), 180, text=((g(6), g(50)), (g(6), g(51.5)), 'right'))
for pin, net in (('1', 'IN'), ('2', 'OUT')):
    q = P('J2', pin); W(q, (q[0] + g(3), q[1])); lab(net, (q[0] + g(3), q[1]))
q = P('J2', '3'); W(q, (q[0] + g(3), q[1])); GND((q[0] + g(3), q[1]))

# ================================================================ INPUT BUFFER
s.box('INPUT BUFFER (U1A): clean signal for the drive stage and the detector', g(42), g(6), g(100), g(36))
y = g(16)
lab('IN', (g(45), y), 'l'); W((g(45), y), (g(50), y))
Rv('R3', '1M', g(50), y + g(3.5), side='l', d='Input pull-down'); W((g(50), y), P('R3', '1')); GND(P('R3', '2'))
W((g(50), y), (g(52), y)); Ch('C5', '220n', g(53.5), y, d='Input coupling (film)')
W((g(52), y), P('C5', '1')); W(P('C5', '2'), (g(58), y))
Rv('R4', '1M', g(58), y + g(3.5), side='r', d='Bias to VB'); W((g(58), y), P('R4', '1'))
q = P('R4', '2'); W(q, (q[0], q[1] + g(1))); lab('VB', (q[0], q[1] + g(1)), 'l')
OP('U1', 'OPA2134', 1, g(68), y + 2.54)
W((g(58), y), P('U1', '3'))
o = P('U1', '1'); m = P('U1', '2')
W(m, (m[0] - g(1), m[1]), (m[0] - g(1), m[1] + g(3)), (o[0] + g(1), m[1] + g(3)), (o[0] + g(1), o[1]))
W(o, (o[0] + g(1), o[1]), (o[0] + g(5), o[1])); lab('DRY', (o[0] + g(5), o[1]))

# ================================================================ DRIVE STAGE
s.box('DRIVE STAGE (U1B): gain = 1 + R5 / ((R6 + DRIVE) || (R7 + DEPTH + LDR)); diodes cap the output', g(42), g(40), g(150), g(112))
x0, y1 = g(78), g(50)
lab('DRY', (x0 - g(14), y1), 'l')
OP('U1', 'OPA2134', 2, x0, y1 + 2.54)
W((x0 - g(14), y1), P('U1', '5'))
mi = P('U1', '6'); ou = P('U1', '7')
fbL, fbR = mi[0] - g(2), ou[0] + g(2)
fy = mi[1] + g(5)
W(mi, (fbL, mi[1])); W((fbL, mi[1]), (fbL, fy + g(9)))
W(ou, (fbR, ou[1])); W((fbR, ou[1]), (fbR, fy + g(9)))
Rh('R5', '100k', (fbL + fbR) / 2, fy, d='Feedback: sets the gain range')
W((fbL, fy), P('R5', '1')); W(P('R5', '2'), (fbR, fy))
Ch('C6', '100p', (fbL + fbR) / 2, fy + g(3), d='Treble roll-off: 16 kHz with R5 100k (try 47p-470p)')
W((fbL, fy + g(3)), P('C6', '1')); W(P('C6', '2'), (fbR, fy + g(3)))
# clipping diodes, selected by SW1 (ON-OFF-ON): Si pair, off, or red LED pair (anti-parallel, node X to the output)
dy = fy + g(9)
ys = dy + g(6.5)
W((fbL, fy + g(9)), (fbL, ys))
s.part('SW1', 'Switch', 'SW_SPDT', 'CLIP', fbL + 5.08, ys, 0, desc='CLIP: Si / off / LED (ON-OFF-ON mini toggle)',
       text=((fbL + g(1), ys + g(4)), (fbL + g(1), ys + g(5.5)), 'left'), extra={'Panel': 'CLIP'})
t1 = P('SW1', '1'); t3 = P('SW1', '3')
xa = fbL + g(5)
def pair(r1, r2, val, part, y):
    s.part(r1, 'Device', part, val, xa + g(3), y, 0, desc=f'Clipping {val}', text='t')
    s.part(r2, 'Device', part, val, xa + g(3), y + g(3), 180, desc=f'Clipping {val}', text='b')
    W((xa, y), P(r1, '1')); W((xa, y), (xa, y + g(3)), P(r2, '2'))
    W(P(r1, '2'), (fbR, y)); W(P(r2, '1'), (fbR, y + g(3)))
pair('D2', 'D3', '1N4148', 'D', dy + g(1))
pair('D4', 'D5', 'red LED', 'LED', dy + g(9))
W(t1, (xa, t1[1]), (xa, dy + g(4)))
W(t3, (xa, t3[1]), (xa, dy + g(9)))
W((fbR, fy + g(9)), (fbR, dy + g(12)))
# ground legs from the - node: R6 + DRIVE (resting gain) and R7 + DEPTH + LDR (envelope gain)
gx1 = fbL - g(6); gx2 = fbL - g(14)
W((fbL, mi[1]), (gx2, mi[1]))
Rv('R6', '1k', gx1, mi[1] + g(3.5), side='r', d='Max-gain limit (x101)'); W((gx1, mi[1]), P('R6', '1'))
top = rheo_to_vb('RV1', 'C100k', 'DRIVE', gx1, P('R6', '2')[1] + g(1))
W(P('R6', '2'), top)
Rv('R7', '1k', gx2, mi[1] + g(3.5), side='l', d='Limits the LDR leg (max envelope gain)'); W((gx2, mi[1]), P('R7', '1'))
top2 = P('R7', '2')[1] + g(1)
POT('RV2', 'B50k', 'DEPTH', gx2, top2 + 3.81, text=((gx2 - g(5), top2 + g(1)), (gx2 - g(5), top2 + g(2.5)), 'right'))
W(P('R7', '2'), P('RV2', '3'))
w2 = P('RV2', '2'); p1 = P('RV2', '1')
W(w2, (w2[0] + g(1), w2[1]), (w2[0] + g(1), p1[1] + g(1)), (p1[0], p1[1] + g(1)))
W(p1, (p1[0], p1[1] + g(3))); lab('LDR_A', (p1[0], p1[1] + g(3)), 'l')
W((fbR, ou[1]), (fbR + g(6), ou[1])); lab('DRIVEN', (fbR + g(6), ou[1]))
s.text('DRIVE sets the resting gain (x2 to x101). Picking harder lights the LDR, which pulls the ground leg down through DEPTH:', g(44), g(104))
s.text('more gain, more clipping. The diodes hold the output at about +-0.6 V (Si) / +-1.8 V (LED), so U1B never clips.', g(44), g(107))
s.text('LDR_B goes to VB. Off-board: the pots and switch; everything else fits a breadboard.', g(44), g(110))

# ================================================================ DETECTOR (Flatline+ side chain, fed from DRY)
s.box('DETECTOR (U2): fed from the CLEAN signal through SENSE; full-wave bridge into the vactrol LED', g(154), g(6), g(262), g(80))
y2 = g(18)
lab('DRY', (g(157), y2 - g(4)), 'l'); W((g(157), y2 - g(4)), (g(162), y2 - g(4)))
POT('RV3', 'B100k', 'SENSE', g(162), y2, text=((g(158), y2 + g(3)), (g(158), y2 + g(4.5)), 'right'))
W((g(162), y2 - g(4)), P('RV3', '3'))
q = P('RV3', '1'); W(q, (q[0], q[1] + g(1))); lab('VB', (q[0], q[1] + g(1)), 'l')
def inv(unit, x, ytop, rin, rf, rf_val, cf, out_lab, in_pt=None, in_lab=None):
    OP('U2', 'TL072', unit, x, ytop + 2.54)
    pl, mi, ou = (P('U2', '3'), P('U2', '2'), P('U2', '1')) if unit == 1 else (P('U2', '5'), P('U2', '6'), P('U2', '7'))
    W(pl, (pl[0] - g(6), pl[1])); lab('VB', (pl[0] - g(6), pl[1]), 'l')
    Rh(rin, '10k', mi[0] - 6.35, mi[1]); W(P(rin, '2'), mi)
    q = P(rin, '1')
    if in_pt: W(in_pt, (in_pt[0], q[1]), q)
    else: W(q, (q[0] - g(2), q[1])); lab(in_lab, (q[0] - g(2), q[1]), 'l')
    tap = P(rin, '2'); fy = mi[1] + g(4); rx = ou[0] + g(1)
    W(tap, (tap[0], fy))
    Rh(rf, rf_val, (tap[0] + rx) / 2, fy); W((tap[0], fy), P(rf, '1')); W(P(rf, '2'), (rx, fy))
    bot = fy
    if cf:
        Ch(cf, '220p', (tap[0] + rx) / 2, fy + g(3)); W((tap[0], fy), (tap[0], fy + g(3)), P(cf, '1')); W(P(cf, '2'), (rx, fy + g(3))); bot = fy + g(3)
    W(ou, (rx, ou[1])); W((rx, ou[1]), (rx, bot))
    W((rx, ou[1]), (rx + g(4), ou[1])); lab(out_lab, (rx + g(4), ou[1]))
inv(1, g(182), y2 - g(2.5), 'R8', 'R9', '100k', 'C7', 'SC_N', in_pt=P('RV3', '2'))
inv(2, g(182), g(42), 'R10', 'R11', '10k', None, 'SC_P', in_lab='SC_N')
bx, by = g(222), g(36)
lab('SC_P', (g(204), by), 'l')
Rh('R12', '330', g(209), by, d='LED current limit')
W((g(204), by), P('R12', '1'))
BA, BB, BP, BN = (bx - g(8), by), (bx + g(8), by), (bx, by - g(8)), (bx, by + g(8))
W(P('R12', '2'), BA)
lab('SC_N', (BB[0] + g(5), BB[1])); W(BB, (BB[0] + g(5), BB[1]))
for ref, x, yy, txt in (('D6', BA[0], by - g(4), 'l'), ('D7', BB[0], by - g(4), 'r'), ('D8', BA[0], by + g(4), 'l'), ('D9', BB[0], by + g(4), 'r')):
    s.part(ref, 'Device', 'D_Schottky', '1N5817', x, yy, 270, desc='Bridge', text=txt)
for ref, an, ca in (('D6', BA, BP), ('D7', BB, BP), ('D8', BN, BA), ('D9', BN, BB)):
    s.L(P(ref, '2'), an, first='v'); s.L(P(ref, '1'), ca, first='v')
W(BP, (BP[0], BP[1] - g(2))); lab('BR_P', (BP[0], BP[1] - g(2)))
W(BN, (BN[0], BN[1] + g(2))); lab('BR_N', (BN[0], BN[1] + g(2)))
# LED string + release cap
lx = g(238)
lab('BR_P', (lx, g(14)), 'l'); W((lx, g(14)), (lx + g(3), g(14)))
s.part('D10', 'Device', 'LED', 'GR LED', lx + g(3), g(18), 90, desc='Activity LED (optional: jumper it out to lower the threshold)', text='r')
W((lx + g(3), g(14)), P('D10', '2'))
s.part('U3', 'Isolator', 'NSL-32', 'VTL5C3', lx + g(11), g(26), 0, desc='VTL5C3 / Xvive, or DIY red LED + LDR in heat-shrink',
       text=((lx + g(11), g(21)), (lx + g(11), g(22.5)), None))
W(P('D10', '1'), (P('D10', '1')[0], P('U3', '1')[1]), P('U3', '1'))
k = P('U3', '2'); W(k, (lx + g(3), k[1]), (lx + g(3), g(32)))
s.part('RV4', 'Device', 'R_Potentiometer_Trim', '1k', lx + g(3), g(32) + 3.81, 0, desc='LED current trim', text='l')
W((lx + g(3), g(32)), P('RV4', '1'))
w2 = P('RV4', '2'); p3 = P('RV4', '3')
W(w2, (w2[0] + g(1), w2[1]), (w2[0] + g(1), p3[1] + g(1)), (p3[0], p3[1] + g(1)))
W(p3, (p3[0], g(42))); lab('BR_N', (p3[0], g(42)), 'l')
q = P('U3', '4'); W(q, (q[0] + g(3), q[1])); lab('LDR_A', (q[0] + g(3), q[1]))
q = P('U3', '3'); W(q, (q[0] + g(3), q[1])); lab('VB', (q[0] + g(3), q[1]))
lab('BR_P', (g(238), g(52)), 'l'); lab('BR_N', (g(238), g(64)), 'l')
W((g(238), g(52)), (g(242), g(52))); CPv('C8', '220u', g(242), g(58), d='Release: 220u (Flatline stock); try 100u-470u')
W((g(242), g(52)), P('C8', '1')); W(P('C8', '2'), (g(242), g(64))); W((g(238), g(64)), (g(242), g(64)))
s.text('SENSE: how hard you must pick to light the LDR. U2A gain 10, U2B unity inverter: bridge sees 0-20x DRY.', g(156), g(74))
s.text('LDR_A goes to the DEPTH leg of the drive stage, LDR_B (pin 3) to VB.', g(156), g(77))

# ================================================================ OUTPUT
s.box('OUTPUT: TONE (hi-cut) + VOLUME', g(154), g(84), g(262), g(112))
lab('DRIVEN', (g(157), g(94)), 'l')
Rh('R13', '1k', g(162), g(94)); W((g(157), g(94)), P('R13', '1'))
W(P('R13', '2'), (g(168), g(94)))
POT('RV5', 'B50k', 'TONE', g(170), g(94) + 3.81, mirror=None, text=((g(172), g(91)), (g(172), g(92.5)), 'left'))
W((g(168), g(94)), (g(170), g(94)), P('RV5', '1'))
w = P('RV5', '2'); p3 = P('RV5', '3')
W(w, (w[0] + g(1), w[1]), (w[0] + g(1), p3[1] + g(1)), (p3[0], p3[1] + g(1)))
W(p3, (p3[0], p3[1] + g(3)), (g(180), p3[1] + g(3)))
Cv('C9', '10n', g(180), p3[1] + g(3) + 3.81 + g(0), side='r', d='Hi-cut: 16 kHz (TONE min) to 310 Hz (max)')
W((g(180), p3[1] + g(3)), P('C9', '1')); GND(P('C9', '2'))
W((g(180), p3[1] + g(3)), (g(186), p3[1] + g(3)))
Ch('C10', '10u', g(189.5), p3[1] + g(3), d='Output coupling')
W((g(186), p3[1] + g(3)), P('C10', '1')); W(P('C10', '2'), (g(196), p3[1] + g(3)))
POT('RV6', 'A100k', 'VOLUME', g(196), p3[1] + g(3) + 3.81)
GND(P('RV6', '1'))
w = P('RV6', '2'); W(w, (g(206), w[1])); lab('OUT', (g(206), w[1]))

s.write(OUT, title_block={'title': 'Clean-Up Drive (breadboard)', 'rev': '0.1', 'company': 'Super-Freq',
                         'comments': ['Optical drive whose gain follows the clean pick envelope (Flatline / Punch Line style)',
                                      'Hard picking clips, soft picking and decays clean up']})
print('written', OUT)
